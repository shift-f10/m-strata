__device__ __forceinline__ float iq_warp_sum(float v) {
#pragma unroll
  for (int o = 16; o > 0; o >>= 1) v += __shfl_xor_sync(0xffffffffu, v, o);
  return v;
}

// One output row against one Q8_1 activation column, the whole warp; (block, part) is lane-strided.
template <int TY>
__device__ __forceinline__ float iq_row_dot(const uint8_t* row, const block_q8_1* x, int nb, int lane) {
  using F = Fmt<TY>;
  float s = 0.0f;
  for (int k = lane; k < nb * F::ipb; k += 32) {
    const int kbx = k / F::ipb, iqs = F::step * (k % F::ipb);
    s += F::dot(row, x + kbx * (F::qk / 32), kbx, iqs);
  }
  return iq_warp_sum(s);
}

template <int TY>
__global__ void __launch_bounds__(128)
    iq_mmvq_kernel(const uint8_t* __restrict__ w, std::size_t row_bytes, const block_q8_1* __restrict__ x,
                   float* __restrict__ y, int n_in, int n_out) {
  const int row = (int)blockIdx.x * 4 + (int)threadIdx.y;
  if (row >= n_out) return;
  const int lane = (int)threadIdx.x;
  const int nb = n_in / Fmt<TY>::qk;  // ggml blocks per row (256/64/32-elem depending on the type)
  const float s = iq_row_dot<TY>(w + (std::size_t)row * row_bytes, x, nb, lane);
  if (lane == 0) y[row] = s;
}

// iq_mmvq_kernel over NC activation columns (the speculative verify window): the same row-per-warp mapping and
// the same iq_row_dot per column, so every column is BITWISE a single-column call; the row's weights are read
// from DRAM once for all NC columns.
template <int TY, int NC>
__global__ void __launch_bounds__(128)
    iq_mmvq_multi_kernel(const uint8_t* __restrict__ w, std::size_t row_bytes, const block_q8_1* __restrict__ x,
                         long long x_stride, float* __restrict__ y, int n_in, int n_out) {
  const int row = (int)blockIdx.x * 4 + (int)threadIdx.y;
  if (row >= n_out) return;
  const int lane = (int)threadIdx.x;
  const int nb = n_in / Fmt<TY>::qk;
  const uint8_t* rowp = w + (std::size_t)row * row_bytes;
#pragma unroll
  for (int c = 0; c < NC; ++c) {
    const float s = iq_row_dot<TY>(rowp, x + (long long)c * x_stride, nb, lane);
    if (lane == 0) y[(long long)c * n_out + row] = s;
  }
}

// The k routed experts of one layer in ONE launch (blockIdx.y = j). Expert e = ids[j]; its matrix base is
// chosen on the device -- a resident VRAM slot when res[e] >= 0, else the expert's matrix in the pinned host
// arena, read zero-copy over PCIe -- so the MoE needs no host-side planning (and no per-layer id sync).
template <int TY>
__global__ void __launch_bounds__(128)
    iq_mmvq_grouped_kernel(const int* __restrict__ ids, const int* __restrict__ eff,
                           const uint8_t* __restrict__ vram_base, long long slot_bytes, long long mat_off,
                           const uint8_t* __restrict__ stage_base, long long stage_stride,
                           const uint8_t* __restrict__ host_base, long long host_stride, std::size_t row_bytes,
                           const block_q8_1* __restrict__ x, long long x_stride_blocks, int x_group,
                           float* __restrict__ y, long long y_stride, int n_in, int n_out) {
  // A zero-copy (non-resident, unstaged) expert is staged first: the block's 4 rows are contiguous, so its
  // 128 threads copy them into shared memory with coalesced 16-byte loads instead of the vec_dot's scattered
  // small reads (nsys: ~7-10 GB/s effective, the grouped launches' whole cost).
  constexpr int kStageBytes = 4 * 1408;  // 4 rows of up to 1408 B (IQ4_XS at n_in 2560 is 1360)
  __shared__ __align__(16) uint8_t stage[kStageBytes];
  const int row0 = (int)blockIdx.x * 4;
  const int row = row0 + (int)threadIdx.y;
  const int j = (int)blockIdx.y;
  const int code = eff[j];
  const int lane = (int)threadIdx.x;
  if (code == kEffSkip || code == kEffCpu) {  // a skipped tail expert or the CPU's: zero rows, nothing read
    if (row < n_out && lane == 0) y[(long long)j * y_stride + row] = 0.0f;
    return;
  }
  const int slot = code;
  const uint8_t* w = code >= 0             ? vram_base + (long long)code * slot_bytes + mat_off
                     : code <= kEffStage0 ? stage_base + (long long)(kEffStage0 - code) * stage_stride + mat_off
                                          : host_base + (long long)ids[j] * host_stride;
  const uint8_t* rowp = w + (std::size_t)row * row_bytes;
  const int nrows = min(4, n_out - row0);
  const std::size_t span = (std::size_t)nrows * row_bytes;
  if (slot == kEffZeroCopy && span <= (std::size_t)kStageBytes && (row_bytes & 3) == 0) {  // block-uniform
    const uint8_t* src8 = w + (std::size_t)row0 * row_bytes;
    const int tid = (int)(threadIdx.y * 32 + threadIdx.x);
    if ((reinterpret_cast<std::uintptr_t>(src8) & 15) == 0) {  // 16-byte loads: 2 KB in flight a block
      const uint4* src = reinterpret_cast<const uint4*>(src8);
      uint4* dst = reinterpret_cast<uint4*>(stage);
      const std::size_t n16 = span / 16;
      for (std::size_t i = (std::size_t)tid; i < n16; i += 128) dst[i] = src[i];
      for (std::size_t i = n16 * 16 + (std::size_t)tid * 4; i < span; i += 512)
        *reinterpret_cast<unsigned*>(stage + i) = *reinterpret_cast<const unsigned*>(src8 + i);
    } else {
      const unsigned* src = reinterpret_cast<const unsigned*>(src8);
      unsigned* dst = reinterpret_cast<unsigned*>(stage);
      for (std::size_t i = (std::size_t)tid; i < span / 4; i += 128) dst[i] = src[i];
    }
    __syncthreads();
    rowp = stage + (std::size_t)threadIdx.y * row_bytes;
  }
  if (row >= n_out) return;
  const int nb = n_in / Fmt<TY>::qk;
  const float s = iq_row_dot<TY>(rowp, x + (long long)(j / x_group) * x_stride_blocks, nb, lane);
  if (lane == 0) y[(long long)j * y_stride + row] = s;
}

// Copy `bytes` from mapped host memory to VRAM with the threads of blockIdx.y's gridDim.x blocks: 16-byte
// loads when both ends are 16-aligned (the link's rate needs many in flight), else 4-byte, else bytes.
__device__ __forceinline__ void stage_copy(uint8_t* __restrict__ dst, const uint8_t* __restrict__ src,
                                           long long bytes) {
  const long long tid = (long long)blockIdx.x * blockDim.x + threadIdx.x;
  const long long nt = (long long)gridDim.x * blockDim.x;
  const std::uintptr_t a = reinterpret_cast<std::uintptr_t>(dst) | reinterpret_cast<std::uintptr_t>(src);
  if ((a & 15) == 0) {
    const long long n16 = bytes / 16;
    const uint4* s = reinterpret_cast<const uint4*>(src);
    uint4* d = reinterpret_cast<uint4*>(dst);
    for (long long i = tid; i < n16; i += nt) d[i] = s[i];
    for (long long i = n16 * 16 + tid; i < bytes; i += nt) dst[i] = src[i];
  } else if ((a & 3) == 0) {
    const long long n4 = bytes / 4;
    const unsigned* s = reinterpret_cast<const unsigned*>(src);
    unsigned* d = reinterpret_cast<unsigned*>(dst);
    for (long long i = tid; i < n4; i += nt) d[i] = s[i];
    for (long long i = n4 * 4 + tid; i < bytes; i += nt) dst[i] = src[i];
  } else {
    for (long long i = tid; i < bytes; i += nt) dst[i] = src[i];
  }
}

// expert_route_plan: blockIdx.y = j (one routed expert), gridDim.x blocks share its copy.
__global__ void expert_route_plan_kernel(const int* __restrict__ ids, const int* __restrict__ res,
                                         const int* __restrict__ tail_rank_dev,
                                         const uint8_t* __restrict__ src_gate, long long gate_stride,
                                         long long gate_bytes, const uint8_t* __restrict__ src_up,
                                         long long up_stride, long long up_bytes,
                                         const uint8_t* __restrict__ src_down, long long down_stride,
                                         long long down_bytes, uint8_t* __restrict__ stage, long long stage_stride,
                                         int k_per_tok, int* __restrict__ eff) {
  const int j = (int)blockIdx.y;
  const int e = ids[j];
  const int slot = res[e];
  const bool lead = blockIdx.x == 0 && threadIdx.x == 0;
  if (slot >= 0) {
    if (lead) eff[j] = slot;
    return;
  }
  const int tail_rank = *tail_rank_dev;
  if (tail_rank > 0 && j % k_per_tok >= tail_rank) {  // the entry's rank within its own token
    if (lead) eff[j] = kEffSkip;
    return;
  }
  if (stage == nullptr) {
    if (lead) eff[j] = kEffZeroCopy;
    return;
  }
  if (lead) eff[j] = kEffStage0 - j;
  uint8_t* dst = stage + (long long)j * stage_stride;
  stage_copy(dst, src_gate + (long long)e * gate_stride, gate_bytes);
  stage_copy(dst + gate_bytes, src_up + (long long)e * up_stride, up_bytes);
  stage_copy(dst + gate_bytes + up_bytes, src_down + (long long)e * down_stride, down_bytes);
}

// One-element-per-thread dequant of an IQ4_XS buffer (n % 256 == 0) to f32 -- for the qwen4exp token
// embedding gather (a quantized token_embd row -> f32), mirroring dequant_q6k. ggml dequantize_row_iq4_xs.
__device__ __forceinline__ float iq4xs_elem(const uint8_t* __restrict__ w, int i) {
  const block_iq4_xs* blk = (const block_iq4_xs*)w + i / 256;
  const int local = i % 256, g = local / 32, within = local % 32;
  const float d = __half2float(blk->d);
  const int ls = ((blk->scales_l[g / 2] >> (4 * (g & 1))) & 0x0F) | (((blk->scales_h >> (2 * g)) & 0x03) << 4);
  const float dl = d * (float)(ls - 32);
  const int qidx = g * 16 + (within & 15);
  const int nib = within < 16 ? (blk->qs[qidx] & 0x0F) : (blk->qs[qidx] >> 4);
  return dl * (float)kvalues_iq4nl[nib];
}
__global__ void dequant_iq4xs_kernel(const uint8_t* __restrict__ w, int n, float* __restrict__ out) {
  const int i = (int)(blockIdx.x * blockDim.x + threadIdx.x);
  if (i >= n) return;
  out[i] = iq4xs_elem(w, i);
}
// The embedding-row gather with the row index on the DEVICE (row = *d_row): graph-capturable.
__global__ void dequant_iq4xs_row_kernel(const uint8_t* __restrict__ table, std::size_t row_bytes,
                                         const int* __restrict__ d_row, int n, float* __restrict__ out) {
  const int i = (int)(blockIdx.x * blockDim.x + threadIdx.x);
  if (i >= n) return;
  out[i] = iq4xs_elem(table + (std::size_t)d_row[0] * row_bytes, i);
}


// ---- the CPU expert lane's device half (see u_iq.cuh) ----
__global__ void expert_lane_plan_kernel(const int* __restrict__ ids, const int* __restrict__ res, int n, int kpt,
                                        const int* __restrict__ tail_rank_dev, const int* __restrict__ lane,
                                        int* __restrict__ eff, int* __restrict__ ncpu) {
  __shared__ int first[kLaneMaxEntries];  // the entry of an expert's first appearance (routing order)
  __shared__ int minr[kLaneMaxEntries];   // per distinct expert: its best rank over the window's tokens
  __shared__ int code[kLaneMaxEntries];   // per distinct expert: its eff code
  const int i = (int)threadIdx.x;
  if (i < n) {
    const int e = ids[i];
    int f = i;
    for (int j = 0; j < i; ++j)
      if (ids[j] == e) {
        f = j;
        break;
      }
    first[i] = f;
    code[i] = res[e];  // >= 0 resident; the misses are coded below
  }
  __syncthreads();
  if (i < n && first[i] == i) {
    int r = i % kpt;
    for (int j = i + 1; j < n; ++j)
      if (first[j] == i) r = min(r, j % kpt);
    minr[i] = r;
  }
  __syncthreads();
  if (i == 0) {
    const int tail = *tail_rank_dev;
    int nmiss = 0;
    for (int q = 0; q < n; ++q) {
      if (first[q] != q || code[q] >= 0) continue;
      if (tail > 0 && minr[q] >= tail) {  // every token routes it low: neither copied nor computed
        code[q] = kEffSkip;
        continue;
      }
      code[q] = kEffCpu;
      ++nmiss;
    }
    const int m = lane[0] != 0 ? (nmiss * lane[1]) >> 8 : nmiss;  // the GPU's share: the last m misses
    int rank = 0;
    for (int q = 0; q < n; ++q) {
      if (first[q] != q || code[q] != kEffCpu) continue;
      if (rank >= nmiss - m) code[q] = kEffZeroCopy;
      ++rank;
    }
    int cpu = 0;
    for (int q = 0; q < n; ++q) cpu += code[first[q]] == kEffCpu ? 1 : 0;
    *ncpu = cpu;
  }
  __syncthreads();
  if (i < n) eff[i] = code[first[i]];
}

__global__ void lane_doorbell_kernel(const float* __restrict__ x, int nx, const int* __restrict__ ids,
                                     const int* __restrict__ eff, int n, const int* __restrict__ lane,
                                     const int* __restrict__ ncpu, float* m_x, int* m_ids, int* m_eff, unsigned* m_seq,
                                     unsigned want) {
  if (lane[0] == 0) return;
  for (int i = (int)threadIdx.x; i < n; i += (int)blockDim.x) {
    m_ids[i] = ids[i];
    m_eff[i] = eff[i];
  }
  if (*ncpu > 0) {  // the CPU computes some of this layer: it needs the MoE input
    const float4* s = reinterpret_cast<const float4*>(x);
    float4* d = reinterpret_cast<float4*>(m_x);
    for (int i = (int)threadIdx.x; i < nx / 4; i += (int)blockDim.x) d[i] = s[i];
  }
  __threadfence_system();
  __syncthreads();
  if (threadIdx.x == 0) *(volatile unsigned*)m_seq = want;
}

__global__ void lane_merge_kernel(const int* __restrict__ eff, const int* __restrict__ lane,
                                  const int* __restrict__ ncpu, const volatile unsigned* m_flag, unsigned want,
                                  const float4* m_ymiss, float4* __restrict__ parts, int row4) {
  const int j = (int)blockIdx.x;
  if (lane[0] == 0 || *ncpu == 0 || eff[j] != kEffCpu) return;
  if (threadIdx.x == 0) {
    while (*m_flag < want) __nanosleep(100);
    __threadfence_system();
  }
  __syncthreads();
  const float4* s = m_ymiss + (long long)j * row4;
  float4* d = parts + (long long)j * row4;
  for (int i = (int)threadIdx.x; i < row4; i += (int)blockDim.x) d[i] = __ldcv(s + i);  // never a cached line
}

}  // namespace

bool iq_supported(int type) {
  return type == 16 || type == 18 || type == 22 || type == 20 || type == 21 || type == 23 || type == 42;
}

void dequant_iq4xs(const void* w, int n, float* out, void* stream) {
  const int threads = 256;
  const int blocks = (n + threads - 1) / threads;
  dequant_iq4xs_kernel<<<blocks, threads, 0, (cudaStream_t)stream>>>((const uint8_t*)w, n, out);
}

void dequant_iq4xs_row(const void* table, std::size_t row_bytes, const int* d_row, int n, float* out, void* stream) {
  const int threads = 256;
  const int blocks = (n + threads - 1) / threads;
  dequant_iq4xs_row_kernel<<<blocks, threads, 0, (cudaStream_t)stream>>>((const uint8_t*)table, row_bytes, d_row, n,
                                                                         out);
}

std::size_t iq_row_bytes(int type, int n_in) {
  const std::size_t nb256 = (std::size_t)n_in / 256;
  switch (type) {
    case 16: return nb256 * 66;             // IQ2_XXS
    case 22: return nb256 * 82;             // IQ2_S
    case 18: return nb256 * 98;             // IQ3_XXS
    case 21: return nb256 * 110;            // IQ3_S
    case 23: return nb256 * 136;            // IQ4_XS
    case 20: return (std::size_t)n_in / 32 * 18;  // IQ4_NL (32-elem block)
    case 42: return (std::size_t)n_in / 64 * 18;  // Q2_0 (64-elem block)
    default: return 0;
  }
}

// One single-column MMVQ (n_out rows), the ExpertTier's per-expert decode matvec. `x_q8_1` is the
// activation column (n_in/32 Q8_1 blocks). y is [n_out].
void iq_mmvq_col(int type, const void* w, const void* x_q8_1, float* y, int n_in, int n_out, void* stream) {
  const dim3 grid((unsigned)((n_out + 3) / 4));
  const dim3 block(32, 4);
  const auto s = static_cast<cudaStream_t>(stream);
  const std::size_t rb = iq_row_bytes(type, n_in);
  const auto* w8 = static_cast<const uint8_t*>(w);
  const auto* x8 = static_cast<const block_q8_1*>(x_q8_1);
  switch (type) {
    case 16: iq_mmvq_kernel<16><<<grid, block, 0, s>>>(w8, rb, x8, y, n_in, n_out); break;
    case 18: iq_mmvq_kernel<18><<<grid, block, 0, s>>>(w8, rb, x8, y, n_in, n_out); break;
    case 22: iq_mmvq_kernel<22><<<grid, block, 0, s>>>(w8, rb, x8, y, n_in, n_out); break;
    case 21: iq_mmvq_kernel<21><<<grid, block, 0, s>>>(w8, rb, x8, y, n_in, n_out); break;
    case 23: iq_mmvq_kernel<23><<<grid, block, 0, s>>>(w8, rb, x8, y, n_in, n_out); break;
    case 20: iq_mmvq_kernel<20><<<grid, block, 0, s>>>(w8, rb, x8, y, n_in, n_out); break;
    case 42: iq_mmvq_kernel<42><<<grid, block, 0, s>>>(w8, rb, x8, y, n_in, n_out); break;
    default: break;
  }
}

void iq_mmvq_multi(int type, const void* w, const void* x_q8_1, long long x_stride_blocks, float* y, int n_in,
                   int n_out, int ncols, void* stream) {
  if (ncols < 1 || n_out < 1) return;
  const dim3 grid((unsigned)((n_out + 3) / 4));
  const dim3 block(32, 4);
  const auto s = static_cast<cudaStream_t>(stream);
  const std::size_t rb = iq_row_bytes(type, n_in);
  const auto* w8 = static_cast<const uint8_t*>(w);
  const auto* x8 = static_cast<const block_q8_1*>(x_q8_1);
#define U_IQ_MULTI_NC(TY, NC) \
  case NC: iq_mmvq_multi_kernel<TY, NC><<<grid, block, 0, s>>>(w8, rb, x8, x_stride_blocks, y, n_in, n_out); break;
#define U_IQ_MULTI(TY)                                                                                     \
  case TY:                                                                                                 \
    switch (ncols) {                                                                                       \
      U_IQ_MULTI_NC(TY, 1) U_IQ_MULTI_NC(TY, 2) U_IQ_MULTI_NC(TY, 3) U_IQ_MULTI_NC(TY, 4) U_IQ_MULTI_NC(TY, 5) \
      U_IQ_MULTI_NC(TY, 6) U_IQ_MULTI_NC(TY, 7) U_IQ_MULTI_NC(TY, 8) default: break;                      \
    }                                                                                                      \
    break;
  switch (type) {
    U_IQ_MULTI(16) U_IQ_MULTI(18) U_IQ_MULTI(22) U_IQ_MULTI(21) U_IQ_MULTI(23) U_IQ_MULTI(20) U_IQ_MULTI(42)
    default: break;
  }
#undef U_IQ_MULTI
#undef U_IQ_MULTI_NC
}

void expert_route_plan(const int* ids, const int* res, int k, const int* tail_rank, const void* src_gate,
                       long long gate_stride, long long gate_bytes, const void* src_up, long long up_stride,
                       long long up_bytes, const void* src_down, long long down_stride, long long down_bytes,
                       void* stage, long long stage_stride, int* eff, void* stream, int k_per_tok) {
  if (k < 1) return;
  // 40 blocks x 256 threads an expert: ~160 KB of 16-byte loads in flight per missed expert (upstream's
  // fetch_blobs runs 384 x 256 over all of a window's misses).
  const dim3 grid(40u, (unsigned)k);
  expert_route_plan_kernel<<<grid, 256, 0, static_cast<cudaStream_t>(stream)>>>(
      ids, res, tail_rank, static_cast<const uint8_t*>(src_gate), gate_stride, gate_bytes,
      static_cast<const uint8_t*>(src_up), up_stride, up_bytes, static_cast<const uint8_t*>(src_down), down_stride,
      down_bytes, static_cast<uint8_t*>(stage), stage_stride, k_per_tok > 0 ? k_per_tok : k, eff);
}

void expert_lane_plan(const int* ids, const int* res, int n, int k_per_tok, const int* tail_rank, const int* lane,
                      int* eff, int* ncpu, void* stream) {
  if (n < 1 || n > kLaneMaxEntries) return;
  expert_lane_plan_kernel<<<1, kLaneMaxEntries, 0, static_cast<cudaStream_t>(stream)>>>(
      ids, res, n, k_per_tok > 0 ? k_per_tok : n, tail_rank, lane, eff, ncpu);
}

void lane_doorbell(const float* x, int nx, const int* ids, const int* eff, int n, const int* lane, const int* ncpu,
                   float* m_x, int* m_ids, int* m_eff, unsigned* m_seq, unsigned want, void* stream) {
  lane_doorbell_kernel<<<1, 1024, 0, static_cast<cudaStream_t>(stream)>>>(x, nx, ids, eff, n, lane, ncpu, m_x, m_ids,
                                                                          m_eff, m_seq, want);
}

void lane_merge(const int* eff, int n, const int* lane, const int* ncpu, const unsigned* m_flag, unsigned want,
                const float* m_ymiss, float* parts, int width, void* stream) {
  if (n < 1) return;
  lane_merge_kernel<<<(unsigned)n, 128, 0, static_cast<cudaStream_t>(stream)>>>(
      eff, lane, ncpu, m_flag, want, reinterpret_cast<const float4*>(m_ymiss), reinterpret_cast<float4*>(parts),
      width / 4);
}

void iq_mmvq_grouped(int type, const int* ids, const int* eff, const void* vram_base, long long slot_bytes,
                     long long mat_off, const void* stage_base, long long stage_stride, const void* host_base,
                     long long host_stride, const void* x_q8_1, long long x_stride_blocks, float* y,
                     long long y_stride, int n_in, int n_out, int k, void* stream, int x_group) {
  if (k < 1 || n_out < 1) return;
  const dim3 grid((unsigned)((n_out + 3) / 4), (unsigned)k);
  const dim3 block(32, 4);
  const auto s = static_cast<cudaStream_t>(stream);
  const std::size_t rb = iq_row_bytes(type, n_in);
  const auto* vb = static_cast<const uint8_t*>(vram_base);
  const auto* sb = static_cast<const uint8_t*>(stage_base);
  const auto* hb = static_cast<const uint8_t*>(host_base);
  const auto* x8 = static_cast<const block_q8_1*>(x_q8_1);
#define U_IQ_GROUPED(TY)                                                                                     \
  iq_mmvq_grouped_kernel<TY><<<grid, block, 0, s>>>(ids, eff, vb, slot_bytes, mat_off, sb, stage_stride, hb, \
                                                    host_stride, rb, x8, x_stride_blocks, x_group, y, y_stride, \
                                                    n_in, n_out)
  switch (type) {
