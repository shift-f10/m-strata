    case 21: U_IQ_GROUPED(21); break;
    case 23: U_IQ_GROUPED(23); break;
    case 20: U_IQ_GROUPED(20); break;
    case 42: U_IQ_GROUPED(42); break;
    default: break;
  }
#undef U_IQ_GROUPED
}

