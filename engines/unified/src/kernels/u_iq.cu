// ---- llama.cpp helpers (vecdotq.cuh) ----
__device__ __forceinline__ int get_int_b2(const void* x, const int& i32) {
  const uint16_t* x16 = (const uint16_t*)x;
  int x32 = x16[2 * i32 + 0] << 0;
  x32 |= x16[2 * i32 + 1] << 16;
  return x32;
}
__device__ __forceinline__ int get_int_b4(const void* x, const int& i32) { return ((const int*)x)[i32]; }
__device__ __forceinline__ uint32_t unpack_ksigns(const uint8_t v) {
  const uint32_t p = __popc(v) & 1;
  const uint32_t s = v ^ p << 7;
  return s * 0x01010101;
}

// ---- qwen4exp i-quant blocks (ggml-common.h) + the IQ4 non-linear codebook + the table helper ----
typedef struct {
  ggml_half d;
  uint8_t qs[16];  // QK2_0/4, 64 elems @ 2 bits -- Strata-custom routed-expert encoding
} block_q2_0;      // 18 bytes
typedef struct {
  ggml_half d;
  uint8_t qs[QK_K / 4];
  uint8_t qh[QK_K / 32];
  uint8_t signs[QK_K / 8];
  uint8_t scales[QK_K / 64];
} block_iq3_s;  // 110 bytes
typedef struct {
  ggml_half d;
  uint8_t qs[16];  // QK4_NL/2, 32 elems
} block_iq4_nl;    // 18 bytes
typedef struct {
  ggml_half d;
  uint16_t scales_h;
  uint8_t scales_l[QK_K / 64];
  uint8_t qs[QK_K / 2];
} block_iq4_xs;  // 136 bytes
static_assert(sizeof(block_q2_0) == 18 && sizeof(block_iq3_s) == 110 && sizeof(block_iq4_nl) == 18 &&
                  sizeof(block_iq4_xs) == 136,
              "qwen i-quant block sizes");
#include "kernels/u_iq_qwen_tables.inc"  // iq3s_grid[512], kvalues_iq4nl[16] (device)
// Two int2 of codebook values selected by the 8 nibbles of q4 (llama.cpp get_int_from_table_16).
__device__ __forceinline__ int2 get_int_from_table_16(const int& q4, const int8_t* table) {
  const uint32_t* table32 = (const uint32_t*)table;
  uint32_t tmp[2];
  const uint32_t low_high_selection_indices = (0x32103210 | ((q4 & 0x88888888) >> 1));
#pragma unroll
  for (uint32_t i = 0; i < 2; ++i) {
    const uint32_t shift = 16 * i;
    const uint32_t low = __byte_perm(table32[0], table32[1], q4 >> shift);
    const uint32_t high = __byte_perm(table32[2], table32[3], q4 >> shift);
    tmp[i] = __byte_perm(low, high, low_high_selection_indices >> shift);
  }
  return make_int2(__byte_perm(tmp[0], tmp[1], 0x6420), __byte_perm(tmp[0], tmp[1], 0x7531));
}

// ---- the three i-quant vec_dots (one 256-block, Q8_1 activation), verbatim from iq_kernels.cu ----
__device__ __forceinline__ float vec_dot_iq2_xxs_q8_1(const void* __restrict__ vbq,
                                                      const block_q8_1* __restrict__ bq8_1, const int& kbx,
                                                      const int& iqs) {
  const block_iq2_xxs* bq2 = (const block_iq2_xxs*)vbq + kbx;
  const int q2 = get_int_b2(bq2->qs, iqs);
  const uint8_t* aux8 = (const uint8_t*)&q2;
  const uint32_t aux32 = get_int_b2(bq2->qs, iqs + 1);
  int sumi = 0;
#pragma unroll
  for (int k0 = 0; k0 < 8; k0 += 2) {
    const uint2 grid_pos = ((const uint2*)iq2xxs_grid)[aux8[k0 / 2]];
    const uint32_t signs = unpack_ksigns(aux32 >> (7 * k0 / 2));
    const int signs0 = __vcmpne4(signs & 0x08040201, 0);
    const int grid0 = __vsub4(grid_pos.x ^ signs0, signs0);
    const int u0 = get_int_b4(bq8_1[iqs / 2].qs, k0 + 0);
    sumi = __dp4a(grid0, u0, sumi);
    const int signs1 = __vcmpne4(signs & 0x80402010, 0);
    const int grid1 = __vsub4(grid_pos.y ^ signs1, signs1);
    const int u1 = get_int_b4(bq8_1[iqs / 2].qs, k0 + 1);
    sumi = __dp4a(grid1, u1, sumi);
  }
  const int ls = aux32 >> 27 | 1;
  sumi = sumi * ls / 8;
  const float d = __half2float(bq2->d) * __low2float(bq8_1[iqs / 2].ds);
  return d * sumi;
}

__device__ __forceinline__ float vec_dot_iq2_s_q8_1(const void* __restrict__ vbq,
                                                    const block_q8_1* __restrict__ bq8_1, const int& kbx,
                                                    const int& iqs) {
  const block_iq2_s* bq2 = (const block_iq2_s*)vbq + kbx;
  const int qs_packed = get_int_b2(bq2->qs, iqs / 2);
  const uint8_t* qs = (const uint8_t*)&qs_packed;
  const int qh = bq2->qh[iqs / 2];
  const int signs_packed_32 = get_int_b2(bq2->qs, QK_K / 32 + iqs / 2);
  const uint8_t* signs_packed_8 = (const uint8_t*)&signs_packed_32;
  const int ls0 = bq2->scales[iqs / 2] & 0x0F;
  const int ls1 = bq2->scales[iqs / 2] >> 4;
  int sumi0 = 0, sumi1 = 0;
#pragma unroll
  for (int l0 = 0; l0 < 8; l0 += 2) {
    const int* grid_pos = (const int*)(iq2s_grid + (qs[l0 / 2] | ((qh << (8 - l0)) & 0x300)));
    const int signs0 =
        __vcmpne4(((signs_packed_8[l0 / 2] & 0x03) << 7) | ((signs_packed_8[l0 / 2] & 0x0C) << 21), 0x00000000);
    const int signs1 =
        __vcmpne4(((signs_packed_8[l0 / 2] & 0x30) << 3) | ((signs_packed_8[l0 / 2] & 0xC0) << 17), 0x00000000);
    const int grid_l = __vsub4(grid_pos[0] ^ signs0, signs0);
    const int grid_h = __vsub4(grid_pos[1] ^ signs1, signs1);
    const int u0 = get_int_b4(bq8_1[iqs / 2].qs, l0 + 0);
    const int u1 = get_int_b4(bq8_1[iqs / 2].qs, l0 + 1);
    if (l0 < 4) {
      sumi0 = __dp4a(grid_l, u0, sumi0);
      sumi0 = __dp4a(grid_h, u1, sumi0);
    } else {
      sumi1 = __dp4a(grid_l, u0, sumi1);
      sumi1 = __dp4a(grid_h, u1, sumi1);
    }
  }
  const int sumi = (sumi0 * ls0 + sumi1 * ls1 + (sumi0 + sumi1) / 2) / 4;
  const float d = __half2float(bq2->d) * __low2float(bq8_1[iqs / 2].ds);
  return d * sumi;
}

__device__ __forceinline__ float vec_dot_iq3_xxs_q8_1(const void* __restrict__ vbq,
                                                      const block_q8_1* __restrict__ bq8_1, const int& kbx,
                                                      const int& iqs) {
  const block_iq3_xxs* bq3 = (const block_iq3_xxs*)vbq + kbx;
  const int2 q3_packed = make_int2(get_int_b2(bq3->qs, iqs), get_int_b2(bq3->qs, iqs + 1));
  const uint8_t* q3 = (const uint8_t*)&q3_packed;
  const uint32_t aux32 = get_int_b2(bq3->qs, QK_K / 16 + iqs / 2);
  int sumi = 0;
#pragma unroll
  for (int l0 = 0; l0 < 8; l0 += 2) {
    const int2 grid_pos = make_int2(iq3xxs_grid[q3[l0 + 0]], iq3xxs_grid[q3[l0 + 1]]);
    const uint32_t signs = unpack_ksigns(aux32 >> (7 * l0 / 2));
    const int signs0 = __vcmpne4(signs & 0x08040201, 0);
    const int grid_l = __vsub4(grid_pos.x ^ signs0, signs0);
    const int u0 = get_int_b4(bq8_1[iqs / 2].qs, l0 + 0);
    const int signs1 = __vcmpne4(signs & 0x80402010, 0);
    const int grid_h = __vsub4(grid_pos.y ^ signs1, signs1);
    const int u1 = get_int_b4(bq8_1[iqs / 2].qs, l0 + 1);
    sumi = __dp4a(grid_l, u0, sumi);
    sumi = __dp4a(grid_h, u1, sumi);
  }
  const int ls = aux32 >> 28;
  sumi = (ls * sumi + sumi / 2) / 2;
  const float d = __half2float(bq3->d) * __low2float(bq8_1[iqs / 2].ds);
  return d * sumi;
}

// ---- the four qwen4exp i-quant vec_dots (from maya-ref iq_kernels.cu / native_mmvq.cu) ----
__device__ __forceinline__ float vec_dot_iq3_s_q8_1(const void* __restrict__ vbq,
                                                    const block_q8_1* __restrict__ bq8_1, const int& kbx,
                                                    const int& iqs) {
  const block_iq3_s* bq3 = (const block_iq3_s*)vbq + kbx;
  const int2 qs_packed = make_int2(get_int_b2(bq3->qs, iqs + 0), get_int_b2(bq3->qs, iqs + 1));
  const uint8_t* qs = (const uint8_t*)&qs_packed;
  const int qh = bq3->qh[iqs / 2];
  const int signs_packed_32 = get_int_b2(bq3->signs, iqs / 2);
  const uint8_t* signs_packed_8 = (const uint8_t*)&signs_packed_32;
  int sumi = 0;
#pragma unroll
  for (int l0 = 0; l0 < 8; l0 += 2) {
    const int2 grid_pos = make_int2(iq3s_grid[qs[l0 + 0] | ((qh << (8 - l0)) & 0x100)],
                                    iq3s_grid[qs[l0 + 1] | ((qh << (7 - l0)) & 0x100)]);
    const int signs0 = __vcmpne4(((signs_packed_8[l0 / 2] & 0x03) << 7) | ((signs_packed_8[l0 / 2] & 0x0C) << 21), 0);
    const int signs1 = __vcmpne4(((signs_packed_8[l0 / 2] & 0x30) << 3) | ((signs_packed_8[l0 / 2] & 0xC0) << 17), 0);
    const int grid_l = __vsub4(grid_pos.x ^ signs0, signs0);
    const int grid_h = __vsub4(grid_pos.y ^ signs1, signs1);
    sumi = __dp4a(grid_l, get_int_b4(bq8_1[iqs / 2].qs, l0 + 0), sumi);
    sumi = __dp4a(grid_h, get_int_b4(bq8_1[iqs / 2].qs, l0 + 1), sumi);
  }
  sumi *= 1 + 2 * ((bq3->scales[iqs / 4] >> ((iqs << 1) & 0x04)) & 0x0F);
  const float d = __half2float(bq3->d) * __low2float(bq8_1[iqs / 2].ds);
  return d * sumi;
}

__device__ __forceinline__ float vec_dot_iq4_nl_q8_1(const void* __restrict__ vbq,
                                                     const block_q8_1* __restrict__ bq8_1, const int& kbx,
                                                     const int& iqs) {
  const block_iq4_nl* bq4 = (const block_iq4_nl*)vbq + kbx;
  const int* q8 = (const int*)bq8_1->qs + iqs;
  int sumi = 0;
#pragma unroll
  for (int l = 0; l < 2; ++l) {
    const int aux_q4 = get_int_b2(bq4->qs, iqs + l);
    const int2 v = get_int_from_table_16(aux_q4, kvalues_iq4nl);
    sumi = __dp4a(v.x, q8[l + 0], sumi);
    sumi = __dp4a(v.y, q8[l + 4], sumi);
  }
  const float d = __half2float(bq4->d) * __low2float(bq8_1->ds);
  return d * sumi;
}

__device__ __forceinline__ float vec_dot_iq4_xs_q8_1(const void* __restrict__ vbq,
                                                     const block_q8_1* __restrict__ bq8_1, const int& kbx,
                                                     const int& iqs) {
  const block_iq4_xs* bq4 = (const block_iq4_xs*)vbq + kbx;
  int sumi = 0;
#pragma unroll
  for (int j = 0; j < 4; ++j) {
    const int aux_q4 = get_int_b4(bq4->qs, iqs + j);
    const int2 v = get_int_from_table_16(aux_q4, kvalues_iq4nl);
    sumi = __dp4a(v.x, get_int_b4(bq8_1[iqs / 4].qs, j + 0), sumi);
    sumi = __dp4a(v.y, get_int_b4(bq8_1[iqs / 4].qs, j + 4), sumi);
  }
  const int ls = ((bq4->scales_l[iqs / 8] >> (iqs & 0x04)) & 0x0F) | (((bq4->scales_h >> (iqs / 2)) & 0x03) << 4);
  sumi *= ls - 32;
  const float d = __half2float(bq4->d) * __low2float(bq8_1[iqs / 4].ds);
  return d * sumi;
}

// Q2_0 (Strata-custom, 64-elem block). Two q8_1 chunks per block (iqs 0,1). native_mmvq.cu vec_dot_q2_0.
__device__ __forceinline__ float vec_dot_q2_0_q8_1(const void* __restrict__ vbq,
                                                   const block_q8_1* __restrict__ bq8_1, const int& kbx,
                                                   const int& iqs) {
  const block_q2_0* bq2_0 = (const block_q2_0*)vbq + kbx;
  const float d2 = __half2float(bq2_0->d);
  const int16_t* qs = (const int16_t*)bq2_0->qs + iqs * 4;
  const block_q8_1* bq8 = bq8_1 + iqs;
  int sumi = 0;
#pragma unroll
  for (int j = 0; j < 4; ++j) {
    const int q = qs[j];
    const int u = get_int_b4(bq8->qs, j * 2 + 0);
    const int v = get_int_b4(bq8->qs, j * 2 + 1);
    const int qe = __byte_perm(0x020100FF, 0x020100FF, q >> 0);
    const int qo = __byte_perm(0x020100FF, 0x020100FF, q >> 2);
    const int qx = __byte_perm(qe, qo, 0x5140);
    const int qy = __byte_perm(qe, qo, 0x7362);
    sumi = __dp4a(u, qx, sumi);
    sumi = __dp4a(v, qy, sumi);
  }
  return d2 * __low2float(bq8->ds) * sumi;
}

