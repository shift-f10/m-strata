#!/usr/bin/env bash
# SP7 M2 Task 6 (spec D-8): Windows release staging.
#
# Stages the cross-built product executables into an installer input tree
# (strata-<ver>-windows-x86_64/) with the same evidence files as the Linux
# bundle plus a generated installer.nsi (NSIS).  Test and helper executables
# never stage.  The NSIS toolchain under .toolchains/ is attempted and the
# outcome recorded in NSIS_STATUS.txt either way; the actual makensis run and
# the installer runtime proof are owner-box steps (plan Task 6) — this script
# never executes a Windows binary.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
PY="$REPO/.venv-dev/bin/python"
[ -x "$PY" ] || PY="$(command -v python3)"

VERSION=""
OUT=""
BUILD_DIR=""
NOTES_URL="https://secure-strata.invalid/release-notes"

while [ $# -gt 0 ]; do
    case "$1" in
        --version) VERSION="$2"; shift 2 ;;
        --out) OUT="$2"; shift 2 ;;
        --build-dir) BUILD_DIR="$2"; shift 2 ;;
        --notes-url) NOTES_URL="$2"; shift 2 ;;
        --skip-build) shift ;;   # accepted for symmetry; staging never runs Windows binaries
        *) echo "stage_windows: unknown argument: $1" >&2; exit 2 ;;
    esac
done

if [ -z "$VERSION" ] || [ -z "$OUT" ]; then
    echo "usage: stage_windows.sh --version V --out DIR [--build-dir DIR] [--notes-url URL]" >&2
    exit 2
fi
if ! printf '%s' "$VERSION" | grep -Eq '^[A-Za-z0-9._-]{1,64}$'; then
    echo "stage_windows: version must be 1..64 of [A-Za-z0-9._-]: $VERSION" >&2
    exit 2
fi

CMAKE="$REPO/.venv-dev/bin/cmake"
[ -x "$CMAKE" ] || CMAKE="$(command -v cmake)"
if [ -z "$BUILD_DIR" ]; then
    # A release tree is its own hooks-off cross configuration: the
    # windows-llvm-mingw-cross gate preset carries test hooks and the
    # distribution judge (run below) refuses such binaries. Only the two
    # product targets are built; nothing here runs a Windows binary.
    BUILD_DIR="$REPO/secure_frontend/out/build/windows-llvm-mingw-release"
    ( cd "$REPO/secure_frontend" \
        && "$CMAKE" --preset windows-llvm-mingw-cross \
            -B out/build/windows-llvm-mingw-release \
            -DSECURE_FRONTEND_TEST_HOOKS=OFF \
        && "$CMAKE" --build out/build/windows-llvm-mingw-release \
            --target strata strata-secure-server )
fi

NAME="strata-$VERSION-windows-x86_64"
BUNDLE="$OUT/$NAME"
if [ -e "$BUNDLE" ]; then
    echo "stage_windows: refusing to reuse an existing staging directory: $BUNDLE" >&2
    exit 1
fi
mkdir -p "$BUNDLE/bin"

for bin in strata.exe strata-secure-server.exe; do
    if [ ! -f "$BUILD_DIR/$bin" ]; then
        echo "stage_windows: required product executable missing: $BUILD_DIR/$bin (cross-build first)" >&2
        exit 1
    fi
    cp "$BUILD_DIR/$bin" "$BUNDLE/bin/$bin"
done

printf '%s\n' "$VERSION" > "$BUNDLE/VERSION"
"$PY" "$REPO/scripts/release/make_manifest.py" --version "$VERSION" \
    --out "$BUNDLE/secure-release-manifest.json"
"$PY" "$REPO/scripts/release/sbom.py" --version "$VERSION" \
    --out "$BUNDLE/sbom.spdx.json"
"$PY" "$REPO/scripts/release/make_update_manifest.py" --bundle "$BUNDLE" \
    --version "$VERSION" --frontend-file strata.exe --notes-url "$NOTES_URL" \
    --out "$BUNDLE/manifest.json"

if [ -n "${STRATA_SIGNING_KEY:-}" ]; then
    "$PY" "$REPO/scripts/release/sign.py" --key-file "$STRATA_SIGNING_KEY" \
        --manifest "$BUNDLE/manifest.json" --out "$BUNDLE/manifest.json.sig"
    echo "signed: manifest.json.sig attached"
else
    echo "unsigned: not releasable"
fi

cat > "$BUNDLE/installer.nsi" <<'NSI'
; Generated by scripts/release/stage_windows.sh — do not edit by hand.
; User-level install, no elevation, no network: the installer only lays down
; the staged binaries and the release evidence files.
!include "MUI2.nsh"

Name "Secure Strata"
OutFile "strata-0.0.0-windows-x86_64-installer.exe"
InstallDir "$PROGRAMFILES64\Secure Strata"
RequestExecutionLevel user

!insertmacro MUI_PAGE_DIRECTORY
!insertmacro MUI_PAGE_INSTFILES
!insertmacro MUI_LANGUAGE "English"

Section "Secure Strata"
    SetOutPath "$INSTDIR\bin"
    File "bin\strata.exe"
    File "bin\strata-secure-server.exe"
    SetOutPath "$INSTDIR"
    File "VERSION"
    File "manifest.json"
    File "sbom.spdx.json"
    File "secure-release-manifest.json"
    WriteUninstaller "$INSTDIR\uninstall.exe"
SectionEnd

Section "Uninstall"
    RMDir /r "$INSTDIR\bin"
    Delete "$INSTDIR\VERSION"
    Delete "$INSTDIR\manifest.json"
    Delete "$INSTDIR\sbom.spdx.json"
    Delete "$INSTDIR\secure-release-manifest.json"
    Delete "$INSTDIR\uninstall.exe"
    RMDir "$INSTDIR"
SectionEnd
NSI
sed -i "s/strata-0.0.0-windows/strata-$VERSION-windows/" "$BUNDLE/installer.nsi"

mkdir -p "$REPO/.toolchains"
makensis="$(command -v makensis || true)"
if [ -z "$makensis" ]; then
    for candidate in "$REPO"/.toolchains/*/makensis "$REPO"/.toolchains/*/usr/bin/makensis; do
        if [ -x "$candidate" ]; then makensis="$candidate"; break; fi
    done
fi
if [ -n "$makensis" ]; then
    if probe="$("$makensis" -VERSION 2>&1)"; then
        printf 'makensis: available at %s (%s); the makensis run and installer runtime proof stay owner-box steps (plan Task 6)\n' \
            "$makensis" "$(printf '%s' "$probe" | head -1)" > "$BUNDLE/NSIS_STATUS.txt"
    else
        printf 'makensis: present at %s but not usable here (%s); content staging is verified by the pytest suite and the makensis run is an owner-box step recorded in the kit\n' \
            "$makensis" "$(printf '%s' "$probe" | head -1)" > "$BUNDLE/NSIS_STATUS.txt"
    fi
else
    printf 'makensis: unavailable in this environment; content staging is verified by the pytest suite and the makensis run is an owner-box step recorded in the kit\n' \
        > "$BUNDLE/NSIS_STATUS.txt"
fi

( cd "$BUNDLE" && find . -type f ! -name SHA256SUMS -printf '%P\n' | sort | \
    xargs -d '\n' sha256sum > SHA256SUMS )
( cd "$BUNDLE" && sha256sum -c --quiet SHA256SUMS )

"$PY" "$REPO/scripts/secure_distribution_check.py" --package-dir "$BUNDLE" --release
echo "staged: $BUNDLE"
