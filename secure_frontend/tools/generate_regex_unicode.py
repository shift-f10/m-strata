"""Generate src/regex_unicode_data.inc - the Unicode classes Maya's tokenizer reads - from Python's regex module.

Maya's server tokenizes DeepSeek-V4.1 and MiniMax-M3.1 with tools/strata_tokenizer.py (Maya v1.1.30: the deepseek3 and
minimax pre-tokenizers), whose splits are `regex` patterns over \\p{L}, \\p{M}, \\p{N}, \\p{P}, \\p{S}, the letter
subcategories and \\s. Asking that module which code points each class holds gives the frontend the same classes, at
the module's own Unicode version. Maya's setup installs `regex` unpinned (setup.py PY_PACKAGES), so a current one is the
reference; its version is recorded in the output.

Usage: python -I tools/generate_regex_unicode.py > src/regex_unicode_data.inc
"""
import sys

import regex

# bit, name, pattern - the bits the frontend's regex_unicode::k* constants name
CLASSES = [
    ("kL", r"\p{L}"), ("kM", r"\p{M}"), ("kN", r"\p{N}"), ("kP", r"\p{P}"), ("kS", r"\p{S}"),
    ("kLu", r"\p{Lu}"), ("kLl", r"\p{Ll}"), ("kLt", r"\p{Lt}"), ("kLm", r"\p{Lm}"), ("kLo", r"\p{Lo}"),
    ("kSpace", r"\s"),
]


def main():
    points = [c for c in range(0x110000) if not 0xD800 <= c <= 0xDFFF]  # (a surrogate is never UTF-8 text)
    text = "".join(map(chr, points))
    flags = [0] * 0x110000
    for bit, (_, pattern) in enumerate(CLASSES):
        for m in regex.finditer("(?:%s)+" % pattern, text):
            for i in range(m.start(), m.end()):
                flags[points[i]] |= 1 << bit

    # the splitters' assumptions, checked here: one major class a code point at most, one letter subcategory a letter
    major = (1 << 5) - 1
    subcats = ((1 << 10) - 1) & ~major
    for cpt, f in enumerate(flags):
        m = f & major
        if m & (m - 1):
            sys.exit("U+%04X is in more than one of L, M, N, P, S (0x%03X)" % (cpt, f))
        s = f & subcats
        if bool(f & 1) != bool(s) or (s & (s - 1)):
            sys.exit("U+%04X: a letter must be in exactly one of Lu, Ll, Lt, Lm, Lo (0x%03X)" % (cpt, f))

    ranges = []
    for cpt, f in enumerate(flags):
        if not ranges or ranges[-1][1] != f:
            ranges.append((cpt, f))

    out = []
    w = out.append
    w("// src/regex_unicode_data.inc - GENERATED by tools/generate_regex_unicode.py; do not edit.")
    w("// From Python's regex module %s (Python %s): which code points \\p{L}, \\p{M}, \\p{N}, \\p{P}, \\p{S}, the"
      % (regex.__version__, sys.version.split()[0]))
    w("// letter subcategories and \\s match there - the classes Maya's tokenizer (tools/strata_tokenizer.py) splits by.")
    w("// Included once, by tokenizer_pack.cpp.")
    w("")
    w("namespace regex_unicode {")
    w("")
    w("inline constexpr std::uint16_t " + ", ".join("%s = 0x%03X" % (name, 1 << bit) for bit, (name, _) in enumerate(CLASSES)) + ";")
    w("struct ClassRange { std::uint32_t start; std::uint16_t classes; };")
    w("// [start, the next entry's start): the classes of every code point in it")
    w("inline constexpr std::array<ClassRange, %d> kClassRanges{{" % len(ranges))
    line = ""
    for start, f in ranges:
        item = "{0x%06X, 0x%03X}," % (start, f)
        if len(line) + len(item) + 1 > 118:
            w(line.rstrip())
            line = ""
        line += item + " "
    if line:
        w(line.rstrip())
    w("}};")
    w("")
    w("}  // namespace regex_unicode")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
