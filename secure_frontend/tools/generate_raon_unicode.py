"""Generate src/raon_unicode_data.inc - the Unicode tables raon-1-mini's and flint's tokenizers read - from llama.cpp.

raon1's tokenizer (raon_bpe) normalizes text to NFC and splits it with llama.cpp's hand-written raon pre-tokenizer
(unicode_regex_split_custom_raon). Both read llama.cpp's own Unicode data, so the frontend takes the same tables:
the category flags (number / letter / accent mark), the whitespace set, and the canonical combining classes,
decompositions and compositions NFC uses. The source is KRAFTON's llama.cpp (raon-1-mini-preview), whose
tokenizer is the model's reference; its src/unicode-data.cpp is MIT (Copyright (c) 2023-2026 The ggml authors).

flint's tokenizer (flint_bpe) runs llama.cpp master's three flint regexes over llama.cpp's "collapsed" text, which reads
every category (number, letter, accent mark, punctuation, symbol, and the rest as one "other"), so the flags keep all of
llama.cpp's category bits (MASK_CATEGORIES). llama.cpp master e86f5fd1's src/unicode-data.cpp, flint's reference, is
byte-identical to KRAFTON's, so both tokenizers read the one table.

Usage: python tools/generate_raon_unicode.py <llama.cpp>/src/unicode-data.cpp <commit> > src/raon_unicode_data.inc
"""
import re
import sys

# llama.cpp's unicode_cpt_flags bits (src/unicode.h): the raon splitter reads number / letter / accent mark, the flint
# splitter every category (MASK_CATEGORIES, 0x00FF: undefined, number, letter, separator, accent mark, punctuation,
# symbol, control), each code point carrying exactly one
NUMBER, LETTER, ACCENT_MARK, PUNCTUATION, SYMBOL = 0x0002, 0x0004, 0x0010, 0x0020, 0x0040
KEPT = 0x00FF


def table(text, name):
    """The body of `... name = { ... };` as its lines."""
    m = re.search(r"\b" + name + r"\s*=\s*\{(.*?)\n\};", text, re.S)
    if m is None:
        sys.exit("table %s not found" % name)
    return m.group(1)


def main():
    src, commit = sys.argv[1], sys.argv[2]
    text = open(src, encoding="utf-8").read()

    ranges = [(int(a, 16), int(b, 16)) for a, b in re.findall(r"\{0x([0-9A-Fa-f]+), 0x([0-9A-Fa-f]+)\}",
                                                                table(text, "unicode_ranges_flags"))]
    # merge neighbours whose kept flags agree (the last entry is the end marker, 0x110000)
    merged = []
    for start, flags in ranges:
        kept = flags & KEPT
        if kept & (kept - 1):
            sys.exit("code point 0x%06X carries more than one category (0x%02X)" % (start, kept))
        if merged and merged[-1][1] == kept and start != 0x110000:
            continue
        merged.append((start, kept))
    whitespace = sorted(int(v, 16) for v in re.findall(r"0x([0-9A-Fa-f]+)", table(text, "unicode_set_whitespace")))
    ccc = sorted((int(a, 16), int(b)) for a, b in re.findall(r"\{0x([0-9A-Fa-f]+), (\d+)\}",
                                                             table(text, "unicode_combining_class")))
    dec = sorted((int(a, 16), int(b, 16), int(c, 16)) for a, b, c in re.findall(
        r"\{0x([0-9A-Fa-f]+), \{0x([0-9A-Fa-f]+), 0x([0-9A-Fa-f]+)\}\}", table(text, "unicode_decomposition")))
    comp = sorted((int(a, 16), int(b, 16)) for a, b in re.findall(r"\{0x([0-9A-Fa-f]+)ULL, 0x([0-9A-Fa-f]+)\}",
                                                                 table(text, "unicode_composition")))

    out = []
    w = out.append
    w("// src/raon_unicode_data.inc - GENERATED by tools/generate_raon_unicode.py; do not edit.")
    w("// From krafton-ai/llama.cpp (raon-1-mini-preview) commit %s, src/unicode-data.cpp" % commit)
    w("// (MIT, Copyright (c) 2023-2026 The ggml authors): the tables raon-1-mini's reference tokenizer reads, and flint's")
    w("// (llama.cpp master e86f5fd1, whose src/unicode-data.cpp is byte-identical).")
    w("// Included once, by tokenizer_pack.cpp.")
    w("")
    w("namespace raon_unicode {")
    w("")
    w("// llama.cpp's category flags (MASK_CATEGORIES; one category a code point): [start, the next entry's start)")
    w("inline constexpr std::uint8_t kNumber = 0x%02X, kLetter = 0x%02X, kAccentMark = 0x%02X, kPunctuation = 0x%02X,"
      " kSymbol = 0x%02X;" % (NUMBER, LETTER, ACCENT_MARK, PUNCTUATION, SYMBOL))
    w("struct FlagRange { std::uint32_t start; std::uint8_t flags; };")
    w("inline constexpr std::array<FlagRange, %d> kFlagRanges{{" % len(merged))
    for i in range(0, len(merged), 6):
        w("    " + " ".join("{0x%06X, 0x%02X}," % r for r in merged[i:i + 6]))
    w("}};")
    w("")
    w("// llama.cpp's unicode_set_whitespace, sorted")
    w("inline constexpr std::array<std::uint32_t, %d> kWhitespace{{" % len(whitespace))
    for i in range(0, len(whitespace), 8):
        w("    " + " ".join("0x%06X," % v for v in whitespace[i:i + 8]))
    w("}};")
    w("")
    w("// canonical combining classes (non-zero), sorted by code point")
    w("struct CombiningClass { std::uint32_t cpt; std::uint8_t ccc; };")
    w("inline constexpr std::array<CombiningClass, %d> kCombiningClass{{" % len(ccc))
    for i in range(0, len(ccc), 6):
        w("    " + " ".join("{0x%06X, %d}," % r for r in ccc[i:i + 6]))
    w("}};")
    w("")
    w("// canonical decompositions (one or two code points; second 0: one), sorted by code point")
    w("struct Decomposition { std::uint32_t cpt; std::uint32_t first; std::uint32_t second; };")
    w("inline constexpr std::array<Decomposition, %d> kDecomposition{{" % len(dec))
    for i in range(0, len(dec), 4):
        w("    " + " ".join("{0x%06X, 0x%06X, 0x%06X}," % r for r in dec[i:i + 4]))
    w("}};")
    w("")
    w("// canonical compositions: (first << 32 | second) -> composite, sorted by the pair")
    w("struct Composition { std::uint64_t pair; std::uint32_t composite; };")
    w("inline constexpr std::array<Composition, %d> kComposition{{" % len(comp))
    for i in range(0, len(comp), 4):
        w("    " + " ".join("{0x%016XULL, 0x%06X}," % r for r in comp[i:i + 4]))
    w("}};")
    w("")
    w("}  // namespace raon_unicode")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
